export function translate(lang, key, values = {}) {
  const template = COPY[lang]?.[key] ?? COPY.en[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}
