// Generates the offline data used by dive/index.html:
//   dive/data/world-land.js   – coastline rings (Natural Earth via world-atlas), delta-coded
//   dive/data/passengers.js   – passenger records WITHOUT the historical outcome (kept sealed)
// Run: npm run build:dive-data   (needs devDependencies: npm install --prefix website)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(join(root, "package.json"));
const topojson = require("topojson-client");

const Q = 50; // quantisation: 1/50 degree
const BBOX = [-100, 20, 15, 72]; // North Atlantic window that gets 50 m detail

function rings(topo, objectName) {
  const geo = topojson.feature(topo, topo.objects[objectName]);
  const out = [];
  for (const feature of geo.features ?? [geo]) {
    const polys = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
    for (const poly of polys) out.push(poly[0]); // outer rings only (holes are lakes)
  }
  return out;
}
const bboxOf = (ring) => ring.reduce((b, [x, y]) => [Math.min(b[0], x), Math.min(b[1], y), Math.max(b[2], x), Math.max(b[3], y)], [180, 90, -180, -90]);
const intersects = (a, b) => a[0] <= b[2] && a[2] >= b[0] && a[1] <= b[3] && a[3] >= b[1];

function encode(ring) {
  const flat = [];
  let px = 0, py = 0;
  for (const [lon, lat] of ring) {
    const x = Math.round(lon * Q), y = Math.round(lat * Q);
    if (flat.length && x === px && y === py) continue;
    flat.push(x - px, y - py);
    px = x; py = y;
  }
  return flat;
}

const load = (name) => JSON.parse(readFileSync(require.resolve(`world-atlas/${name}.json`), "utf8"));
const coarse = rings(load("land-110m"), "land").map(encode);
const fine = rings(load("land-50m"), "land")
  .filter((r) => intersects(bboxOf(r), BBOX))
  .map(encode)
  .filter((r) => r.length >= 8);

writeFileSync(
  join(root, "dive/data/world-land.js"),
  `// Generated by scripts/build-dive-data.mjs from Natural Earth (public domain) via world-atlas.\n` +
  `// Rings are delta-coded integer pairs in 1/${Q} degree.\n` +
  `window.WORLD_LAND = ${JSON.stringify({ q: Q, coarse, fine })};\n`
);

// Passenger records: strip the historical outcome and model scores (sealed for the next chapter).
const src = readFileSync(join(root, "data/passenger-data.js"), "utf8");
const json = src.slice(src.indexOf("Object.freeze(") + "Object.freeze(".length, src.lastIndexOf(")"));
const all = JSON.parse(json);
const rows = all.map((p) => [p.id, p.name, p.pclass, p.sex, p.age, p.sibSp, p.parch, p.ticket, p.fare, p.embarked, p.cabin]);
writeFileSync(
  join(root, "dive/data/passengers.js"),
  `// Generated by scripts/build-dive-data.mjs. Fields: id, name, pclass, sex, age|null, sibSp, parch, ticket, fare(£), embarked, cabin|null.\n` +
  `// The historical outcome is deliberately NOT included: it stays sealed in this chapter.\n` +
  `window.DIVE_PASSENGERS = ${JSON.stringify(rows)};\n`
);
console.log(`world-land: ${coarse.length} coarse + ${fine.length} fine rings; passengers: ${rows.length}`);
void pathToFileURL;
